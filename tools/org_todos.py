#!/usr/bin/env python3
"""Fill comitatus/06_To-dos (T134, P57's way): one file per thing waiting on someone, from this code base's main.

  python3 tools/org_todos.py            write the files (the pre-commit hook runs it on main)
  python3 tools/org_todos.py --dry-run  print what it would write

waiting_on_William/: each line of the start-up brief's "Waiting on William" (startup.waiting_on_william: Work list
items left as "your call", Tentative principles, handoffs asking William, board notes for him).
waiting_on_integrator/: each job answered and waiting for review, and each open follow-up (docs/follow-ups.md).
one_day_for_William/: each Parked Work list item: ideas for one day in the future, nothing to do now (William,
2026-11-28).
A file is named <code base>_<ID>_<FIRST_WORDS>.md and says it is generated. Generated files that no longer match
anything are removed; files written by hand (no generated line) are never touched. A checkout that isn't in
comitatus/08_Code_Bases writes nothing."""
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import startup

MARK = "<!-- generated by {base}'s tools/org_todos.py; don't edit: the next commit on main rewrites it -->"
LINE = re.compile(r"^  (\S+) \(([^)]*)\): (.*)$")


def todos_dir(root):
    parent = os.path.dirname(root)
    org = os.path.dirname(parent)
    if os.path.basename(parent) != "08_Code_Bases" or not os.path.isdir(os.path.join(org, "06_To-dos")):
        return None
    return os.path.join(org, "06_To-dos")


def slug(text, words=7):
    w = re.findall(r"[A-Za-z0-9]+", text)[:words]
    return "_".join(x.upper() for x in w) or "ITEM"


def read(root, rel):
    try:
        return open(os.path.join(root, rel), encoding="utf-8").read()
    except OSError:
        return ""


def william_items(root):
    """[(ID, kind, text)] from the brief's Waiting on William lines (one source of truth: startup.py)."""
    log = read(root, "03_Past_Decisions/decision-log.md")
    folder = os.path.join(root, "docs", "handoff")
    entries = {n: read(root, f"docs/handoff/{n}") for n in sorted(os.listdir(folder))} if os.path.isdir(folder) else {}
    board = read(root, "BOARD.md")
    out = []
    work = os.path.join(root, startup.s.WORK_DIR)
    work_entries = ({n[:-3]: read(work, n) for n in sorted(os.listdir(work)) if n.endswith(".md")}
                    if os.path.isdir(work) else None)
    for line in startup.waiting_on_william(log, entries, board, False, work_entries=work_entries):
        m = LINE.match(line)
        if m:
            out.append((m.group(1), m.group(2), m.group(3)))
        elif line.startswith("  Board note: "):
            note = line[len("  Board note: "):]
            out.append(("NOTE", "board note", note))
    return out


def integrator_items(root):
    """[(ID, kind, text)]: answered jobs waiting for review, Open/Picked-up Work list items not waiting on William, and open follow-ups."""
    out = []
    folder = os.path.join(root, "docs", "handoff")
    for n in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
        text = read(root, f"docs/handoff/{n}")
        if re.search(r"\| Status: answered", text):
            title = re.search(r"^### (\S+) — (.*)$", text, re.M)
            if title:
                out.append((title.group(1), "review the job", title.group(2)))
    work = os.path.join(root, startup.s.WORK_DIR)
    work_entries = startup.s.read_entries(work)
    waiting_w = {ident for ident, _ in startup.waiting_rows("", work_entries=work_entries)}
    for ident in startup.s.folder_ids(work):
        entry = work_entries[ident]
        st = entry["meta"].get("Status", "")
        if st == "Open" and ident not in waiting_w:
            out.append((ident, "Work list", entry["title"] or ident))
        elif startup.s.PICKED_UP.match(st):
            m = re.search(r"(\d{4}-\d{2}-\d{2})", st)
            date = m.group(1) if m else ""
            kind = f"Work list, picked up {date}" if date else "Work list, picked up"
            text = f"picked up {date}: {entry['title']}" if date else f"picked up: {entry['title']}"
            out.append((ident, kind, text))
    for line in read(root, "docs/follow-ups.md").split("\n"):
        m = re.match(r"^- (\S+) \(([^)]*)\): (.*)$", line)
        if m:
            out.append((m.group(1), f"follow-up, {m.group(2)}", m.group(3)))
    return out


def one_day_items(root):
    """[(ID, kind, text)]: Parked Work list items, kept for one day in the future."""
    work = os.path.join(root, startup.s.WORK_DIR)
    entries = startup.s.read_entries(work)
    return [(ident, "one day", entries[ident]["title"] or ident) for ident in startup.s.folder_ids(work)
            if entries[ident]["meta"].get("Status", "") == "Parked"]


def files_for(base, items, mark):
    files, seen = {}, {}
    for ident, kind, text in items:
        name = f"{base}_{ident}_{slug(text)}.md"
        seen[name] = seen.get(name, 0) + 1
        if seen[name] > 1:
            name = name[:-3] + f"_{seen[name]}.md"
        files[name] = f"{mark}\n\n# {ident} ({kind})\n\n{text}\n\nFrom {base} (comitatus/08_Code_Bases/{base}).\n"
    return files


def sync(folder, files, mark, dry=False, out=print):
    """Write `files` into folder; remove this generator's files that are no longer listed. Returns changes made."""
    os.makedirs(folder, exist_ok=True)
    changes = 0
    for name in sorted(os.listdir(folder)):
        path = os.path.join(folder, name)
        if name.endswith(".md") and name not in files and read(folder, name).startswith(mark):
            changes += 1
            out(f"remove {os.path.basename(folder)}/{name}")
            if not dry:
                os.remove(path)
    for name, text in files.items():
        if read(folder, name) != text:
            changes += 1
            out(f"write {os.path.basename(folder)}/{name}")
            if not dry:
                open(os.path.join(folder, name), "w", encoding="utf-8").write(text)
    return changes


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if "-h" in argv or "--help" in argv:
        print(__doc__)
        return 0
    root = os.path.realpath(subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True,
                                           text=True).stdout.strip())
    todos = todos_dir(root)
    if todos is None:
        return 0
    base = os.path.basename(root)
    mark = MARK.format(base=base)
    dry = "--dry-run" in argv
    quiet = (lambda *a: None) if "--quiet" in argv else print
    changed = sync(os.path.join(todos, "waiting_on_William"), files_for(base, william_items(root), mark), mark, dry, quiet)
    changed += sync(os.path.join(todos, "waiting_on_integrator"), files_for(base, integrator_items(root), mark), mark,
                    dry, quiet)
    changed += sync(os.path.join(todos, "one_day_for_William"), files_for(base, one_day_items(root), mark), mark, dry, quiet)
    if changed and not dry:
        import comitatus_commit
        comitatus_commit.commit(os.path.dirname(todos), [todos], f"06_To-dos: {base}'s items (generated)", out=quiet)
    return 0


if __name__ == "__main__":
    sys.exit(main())
